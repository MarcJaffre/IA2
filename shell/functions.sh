# Fonction d'affichage et de saisie
MENU_SELECTION() {
 clear
 echo "================================================="
 echo "          MENU PRINCIPAL                         "
 echo "================================================="
 echo "";
 echo "";
 echo "================================================="
 read -p "Sélectionner votre choix ? " REPONSE
 echo "";
}
MENU_CHOIX() {
 while true; do
  MENU_SELECTION
   case "$REPONSE" in
    # ===================================================================
    # Choix incorrect
    *)
     echo "Erreur : Choix invalide ($REPONSE). Veuillez réessayer."
     sleep 2
     ;;
    # ===================================================================
    esac
  done
}

